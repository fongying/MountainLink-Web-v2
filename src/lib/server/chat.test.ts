import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {db} from '$lib/server/db';
import {canAccessChat,listChat,sendChat,acceptChatDelivery,ingestChat} from './chat';
const run=(s:string,p:any[]=[])=>new Promise<void>((r,j)=>db.run(s,p,e=>e?j(e):r()));
await run('CREATE TABLE device_bindings(device_id TEXT,user_id INTEGER)');
await run('CREATE TABLE mx2_samples(node_id TEXT,source_node TEXT,received_at INTEGER,sample_ts INTEGER,data_source TEXT,run_id TEXT)');
await run('CREATE TABLE ai_recommendations(id TEXT,generated_at TEXT)');
await run('CREATE TABLE ai_dispatches(recommendation_id TEXT,payload_json TEXT,delivery_stage TEXT,delivery_packet_id INTEGER)');
await run('INSERT INTO device_bindings VALUES(?,?)',['logical',2]);
assert.equal(await canAccessChat(null,'logical'),false);
assert.equal(await canAccessChat({id:3},'logical'),false);
assert.equal(await canAccessChat({id:2},'logical'),true);
assert.equal(await canAccessChat({id:3,is_admin:1},'logical'),true);
const now=Date.now();await run('INSERT INTO mx2_samples VALUES(?,?,?,?,?,?)',['logical','f6fcf190',now-1000,now-1000,'real','DEV-TEST']);
const id=randomUUID(),user={id:2,username:'tester'};let count=0;
const message=await sendChat('logical',user,{id,text:'私訊測試'},async()=>{count++});
assert.equal(message.stage,'webhook_accepted');
await sendChat('logical',user,{id,text:'私訊測試'},async()=>{count++});assert.equal(count,1);
await assert.rejects(sendChat('logical',user,{id:randomUUID(),text:'另一則'},async()=>{}),/20 秒/);
await assert.rejects(sendChat('logical',user,{id:randomUUID(),text:'中'.repeat(77)},async()=>{}),/228/);
const receipt={id:'chat-'+id,gateway:'!c0c31f54',destination:'!f6fcf190',command_id:'a'.repeat(64),stage:'radio_ack',packet_id:123};
assert.equal(await acceptChatDelivery(receipt),true);await acceptChatDelivery({...receipt,stage:'queued'});
assert.equal((await listChat('logical')).messages[0].stage,'radio_ack');
assert.equal(await acceptChatDelivery({...receipt,destination:'!12345678'}),false);
const incoming={key:'b'.repeat(64),gateway_node:'!c0c31f54',source_node:'f6fcf190',packet_id:456,received_at:now,text:'收到，回覆測試'};
assert.equal((await ingestChat(incoming,now)).assigned,true);
assert.equal((await ingestChat(incoming,now)).status,'existing');
assert.equal((await listChat('logical')).messages.length,2);
await run('INSERT INTO mx2_samples VALUES(?,?,?,?,?,?)',['new-owner','f6fcf190',now+1000,now+1000,'real','NEW']);
const older={...incoming,key:'c'.repeat(64),packet_id:457};assert.equal((await ingestChat(older,now+2000)).assigned,true);
assert.equal((await listChat('logical')).messages.length,3);
const orphan={...incoming,key:'d'.repeat(64),packet_id:458,source_node:'12345678'};assert.equal((await ingestChat(orphan,now)).assigned,false);
assert.equal((await listChat('logical')).messages.length,3);
await assert.rejects(ingestChat({...incoming,source_node:'ffffffff'},now),/無效/);
console.log('CHAT_TESTS_PASSED: ownership, idempotency, cooldown, UTF8, monotonic ACK, inbox dedupe, historical identity, orphan isolation');
db.close();
